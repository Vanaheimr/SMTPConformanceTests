using System.Security.Cryptography.X509Certificates;
using System.Text;

using NUnit.Framework;

using org.GraphDefined.Vanaheimr.Hermod.SMTP.Server;

using SMTPConformance.Core;
using SMTPConformance.Core.Fixtures;
using SMTPConformance.Core.RawSmtp;

namespace SMTPConformance.Auth.Tests;

/// <summary>
/// RFC 4954 §4 in its details: how long a SASL response may be, what base64 it is written in,
/// and what a line too long does to the exchange; RFC 4616 §2: the lengths of PLAIN.
/// </summary>
[TestFixture]
public sealed class SaslExchangeTests : HermodServerTestBase
{

    private const String AlicesPassword = "correct horse battery staple";

    // RFC 4616 §2: "Servers MUST be capable of accepting authzid, authcid, and passwd productions
    // up to and including 255 octets" - an identity and a password of 255 octets each.
    private static readonly String LongIdentity  = new String('u', 255 - "@hermod.test".Length) + "@hermod.test";
    private static readonly String LongPassword  = String.Concat(Enumerable.Range(0, 255).Select(i => (Char) ('a' + i % 26)));

    protected override HermodSmtpServerFixtureOptions Options
        => new() {
               EnableTls  = true,
               Users      = [ new("alice", AlicesPassword), new(LongIdentity, LongPassword) ]
           };

    private static String B64(String Text)
        => Convert.ToBase64String(Encoding.UTF8.GetBytes(Text));

    /// <summary>
    /// Submission port, EHLO, STARTTLS, EHLO - ready for AUTH.
    /// </summary>
    private async Task<RawSmtpClient> SubmissionOverTls()
    {
        var (client, _) = await Server.ConnectSubmissionAsync();
        await client.EhloAsync();
        await client.StartTlsAsync();
        await client.EhloAsync();
        return client;
    }


    #region S-37: the length of a SASL response

    [Test(Description = "RFC 4616 §2: authcid and passwd of 255 octets each, no authzid - its initial response fits a command line of 1024 octets: a guard for the account and for S-37")]
    [Property("Finding", "S-37")]
    public async Task A_long_identity_and_password_without_authzid_sign_in()
    {

        await using var client = await SubmissionOverTls();

        var reply = await client.CommandAsync("AUTH PLAIN " + B64($"\0{LongIdentity}\0{LongPassword}"));

        Assert.That(reply.Code, Is.EqualTo(235), Explain(client));

    }


    [Test(Description = "RFC 4954 §4: \"Clients and servers MUST be able to handle the maximum encoded size of challenges and responses generated by their supported authentication mechanisms\"; RFC 4616 §2: authzid, authcid and passwd up to 255 octets each - 1024 octets of base64, which do not fit a command line of 1024 octets with \"AUTH PLAIN \" in front")]
    [Property("Finding", "S-37")]
    public async Task The_longest_PLAIN_initial_response_signs_in()
    {

        await using var client = await SubmissionOverTls();

        var response = B64($"{LongIdentity}\0{LongIdentity}\0{LongPassword}");
        Assume.That(response.Length, Is.EqualTo(1024));

        var reply = await client.CommandAsync("AUTH PLAIN " + response);

        Assert.That(reply.Code, Is.EqualTo(235), Explain(client));

    }


    [Test(Description = "RFC 4954 §4: \"Note that these [BASE64] strings can be much longer than normal SMTP commands\" - the longest PLAIN response, 1024 octets of base64, on its own line after the empty 334 challenge")]
    [Property("Finding", "S-37")]
    public async Task The_longest_PLAIN_response_after_the_challenge_signs_in()
    {

        await using var client = await SubmissionOverTls();

        var challenge = await client.CommandAsync("AUTH PLAIN");
        Assume.That(challenge.Code, Is.EqualTo(334), Explain(client));

        var reply = await client.CommandAsync(B64($"{LongIdentity}\0{LongIdentity}\0{LongPassword}"));

        Assert.That(reply.Code, Is.EqualTo(235), Explain(client));

    }

    #endregion


    #region S-38: base64 and nothing else

    public static IEnumerable<TestCaseData> NotBase64()
    {

        var response = B64($"\0alice\0{AlicesPassword}");

        TestCaseData Case(String Name, Boolean Initial, String Response)
            => new TestCaseData(Initial, Response).SetName($"Not base64: {Name}")
                                                  .SetProperty("Finding", "S-38");

        yield return Case("a space inside the initial response",   true,  response.Insert(8, " "));
        yield return Case("a space inside the response",           false, response.Insert(8, " "));
        yield return Case("a tab inside the response",             false, response.Insert(8, "\t"));
        yield return Case("a space after the response",            false, response + " ");

        // Convert.FromBase64String refuses these already.
        yield return new TestCaseData(false, response.Insert(8, "=")).SetName("Not base64: a pad character inside the response")
                                                                      .SetProperty("Finding", "S-38");
        yield return new TestCaseData(false, response.TrimEnd('=')).SetName("Not base64: the response without its pad characters")
                                                                    .SetProperty("Finding", "S-38");

    }


    [TestCaseSource(nameof(NotBase64))]
    [Description("RFC 4954 §4: \"servers and clients MUST reject (and not ignore) any character not explicitly allowed by the BASE64 alphabet, and MUST reject any sequence of BASE64 characters that contains the pad character ('=') anywhere other than the end of the string\" - with 501, 5.5.2; the right credentials, written so, sign nobody in")]
    public async Task A_response_that_is_no_base64_is_refused(Boolean Initial, String Response)
    {

        await using var client = await SubmissionOverTls();

        SmtpReply reply;

        if (Initial)
            reply = await client.CommandAsync("AUTH PLAIN " + Response);

        else
        {
            var challenge = await client.CommandAsync("AUTH PLAIN");
            Assume.That(challenge.Code, Is.EqualTo(334), Explain(client));
            reply = await client.CommandAsync(Response);
        }

        Assert.That(reply.Code, Is.EqualTo(501), Explain(client));

    }

    #endregion


    #region S-39: a line too long ends the exchange

    [Test(Description = "RFC 4954 §4: \"If, during an authentication exchange, the server receives a line that is longer than the server's authentication buffer, the server fails the AUTH command with the 500 reply\" - the AUTH command is over, and what follows is a command: NOOP is 250")]
    [Property("Finding", "S-39")]
    public async Task A_line_too_long_in_the_exchange_fails_the_AUTH_command()
    {

        await using var client = await SubmissionOverTls();

        var challenge = await client.CommandAsync("AUTH PLAIN");
        Assume.That(challenge.Code, Is.EqualTo(334), Explain(client));

        // Beyond any authentication buffer: RFC 4954 §4 has 12288 octets as sufficient.
        var tooLong = await client.CommandAsync(new String('A', 20_000));
        var noop    = await client.CommandAsync("NOOP");

        Assert.Multiple(() => {
            Assert.That(tooLong.Code,         Is.EqualTo(500),     Explain(client));
            Assert.That(tooLong.EnhancedCode, Is.EqualTo("5.5.6"), Explain(client));
            Assert.That(noop.Code,            Is.EqualTo(250),     "NOOP is a command, not a SASL response" + Explain(client));
        });

    }


    [Test(Description = "RFC 4954 §4: an exchange cancelled with \"*\" is over - NOOP is 250: a guard for S-39")]
    [Property("Finding", "S-39")]
    public async Task A_cancelled_exchange_is_over()
    {

        await using var client = await SubmissionOverTls();

        var challenge = await client.CommandAsync("AUTH PLAIN");
        Assume.That(challenge.Code, Is.EqualTo(334), Explain(client));

        var cancel = await client.CommandAsync("*");
        var noop   = await client.CommandAsync("NOOP");

        Assert.Multiple(() => {
            Assert.That(cancel.Code, Is.EqualTo(501), Explain(client));
            Assert.That(noop.Code,   Is.EqualTo(250), Explain(client));
        });

    }

    #endregion

}


/// <summary>
/// RFC 4954 §6: a user store that cannot be asked is a temporary failure, not a wrong password.
/// </summary>
[TestFixture]
public sealed class FailingUserStoreTests : HermodServerTestBase
{

    /// <summary>
    /// A user store whose database is down.
    /// </summary>
    private sealed class UnreachableUserStore : IUserStore
    {

        private static Exception Down
            => new IOException("The user database cannot be reached.");

        public Task<UserCredentials?> GetUserAsync(String Username, CancellationToken ct = default)
            => Task.FromException<UserCredentials?>(Down);

        public Task<UserCredentials?> GetUserByCertificateAsync(X509Certificate2 Certificate, CancellationToken ct = default)
            => Task.FromException<UserCredentials?>(Down);

        public Task<Boolean> ValidatePasswordAsync(String Username, String Password, CancellationToken ct = default)
            => Task.FromException<Boolean>(Down);

    }

    protected override HermodSmtpServerFixtureOptions Options
        => new() { EnableTls = true, UserStore = new UnreachableUserStore() };

    private static String B64(String Text)
        => Convert.ToBase64String(Encoding.UTF8.GetBytes(Text));


    public static IEnumerable<TestCaseData> Mechanisms()
    {

        TestCaseData Case(String Mechanism, params String[] Lines)
            => new TestCaseData(Mechanism, Lines).SetName($"A user store that is down: {Mechanism}")
                                                 .SetProperty("Finding", "S-40");

        yield return Case("PLAIN",          "AUTH PLAIN " + B64("\0alice\0correct horse battery staple"));
        yield return Case("LOGIN",          "AUTH LOGIN", B64("alice"), B64("correct horse battery staple"));

    }


    [TestCaseSource(nameof(Mechanisms))]
    [Description("RFC 4954 §6: \"454 4.7.0 Temporary authentication failure - This response to the AUTH command indicates that the authentication failed due to a temporary server failure. The client SHOULD NOT prompt the user for another password in this case\" - not 535, which tells the client the credentials are wrong")]
    public async Task A_user_store_that_is_down_is_a_temporary_failure(String Mechanism, String[] Lines)
    {

        var (client, _) = await Server.ConnectSubmissionAsync();
        await using var __ = client;

        await client.EhloAsync();
        await client.StartTlsAsync();
        await client.EhloAsync();

        SmtpReply reply = null!;
        foreach (var line in Lines)
            reply = await client.CommandAsync(line);

        Assert.Multiple(() => {
            Assert.That(reply.Code,         Is.EqualTo(454),     Explain(client));
            Assert.That(reply.EnhancedCode, Is.EqualTo("4.7.0"), Explain(client));
        });

    }

}
